#!/usr/bin/env python3
"""Generate tests/sqlite_fixture.h: a small tracks database as a C byte array.

The reader in usbsave/sqlite.c is tested against a REAL database rather than a
hand-built page, because the thing it has to get right -- which bytes of a value
live on the leaf page and which on the overflow chain, and where that chain goes --
is exactly the part a hand-built fixture would get wrong in the same way the reader
might.

Regenerate with:

    python3 tests/mk_sqlite_fixture.py

The fixture is deliberately small: a 512-byte page so a modest value overflows,
three rows, and one of them carrying a long TEXT column. Its shape mirrors the
deck's own client database in the ways that matter (a table with an id column and
a text column, values big enough to spill) and in no other way.
"""
import os
import sqlite3
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "sqlite_fixture.h")

# One row's json is longer than a 512-byte page can hold, so it has to overflow.
LONG = ('{"stream_quality":".256k.aac.mp4","name":"Take Out Your Team",'
        '"artists":[{"id":1,"name":"P Money"},{"id":2,"name":"Taiki Nulight"},'
        '{"id":3,"name":"Diligent Fingers"},{"id":4,"name":"Casey Club"}],'
        '"genre":{"id":91,"name":"Bass House"},"bpm":132,'
        '"key":{"camelot_number":12,"camelot_letter":"A","name":"Db Minor"},'
        '"new_release_date":"2026-09-25","release":{"name":"Take Out Your Team"},'
        '"pad":"' + ("x" * 1200) + '"}')

ROWS = [
    (1, "Short", "One Artist", 120, '{"name":"Short","bpm":120}'),
    (2, "Take Out Your Team", "P Money,Taiki Nulight", 132, LONG),
    (3, "Bassline", "Majestic,Layton Giordani", 128,
     '{"name":"Bassline","bpm":128,"genre":{"name":"Bass House"}}'),
]


def build(path):
    if os.path.exists(path):
        os.unlink(path)
    con = sqlite3.connect(path)
    con.execute("PRAGMA page_size=512")
    con.execute("PRAGMA journal_mode=DELETE")
    con.execute("VACUUM")
    con.execute("CREATE TABLE tracks (id PRIMARY KEY, name VARCHAR(200), "
                "artists VARCHAR(255), bpm INTEGER, json TEXT)")
    con.executemany("INSERT INTO tracks (id, name, artists, bpm, json) "
                    "VALUES (?,?,?,?,?)", ROWS)
    con.commit()
    con.close()


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    tmp = os.path.join(HERE, "_fixture.db")
    build(tmp)
    data = open(tmp, "rb").read()
    os.unlink(tmp)

    with open(OUT, "w") as f:
        f.write("/* Generated by tests/mk_sqlite_fixture.py -- do not edit by hand.\n"
                " *\n"
                " * A real SQLite database: a `tracks` table whose second row's `json`\n"
                " * value is too big for its 512-byte page and so lives partly on the\n"
                " * overflow chain. That is the shape the deck's own client database has,\n"
                " * and the shape the reader has to handle.\n"
                " *\n"
                " * The expected values come with it, so a test compares against what was\n"
                " * put in rather than against what the reader happened to return.\n"
                " */\n")
        f.write("#ifndef EP122_TESTS_SQLITE_FIXTURE_H\n"
                "#define EP122_TESTS_SQLITE_FIXTURE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        for rid, _name, _artists, _bpm, js in ROWS:
            f.write('static const char SQLITE_FIXTURE_JSON_%d[] = "%s";\n'
                    % (rid, c_escape(js)))
        f.write("\n")
        f.write("/* %d bytes, page size %d */\n"
                % (len(data), struct.unpack(">H", data[16:18])[0]))
        f.write("static const uint8_t SQLITE_FIXTURE[] = {\n")
        for i in range(0, len(data), 12):
            row = ", ".join("0x%02x" % b for b in data[i:i + 12])
            f.write("    %s,\n" % row)
        f.write("};\n\n")
        f.write("#define SQLITE_FIXTURE_LEN (sizeof(SQLITE_FIXTURE))\n\n")
        f.write("#endif /* EP122_TESTS_SQLITE_FIXTURE_H */\n")
    print("wrote %s (%d bytes, page size %d)"
          % (OUT, len(data), struct.unpack(">H", data[16:18])[0]))


if __name__ == "__main__":
    main()
